function parseCsv(csv) {
    const lines = csv.trim().split(/\r?\n/);
    const records = [];

    for (let i = 1; i < lines.length; i++) {
        const line = lines[i].trim();
        if (!line) continue;

        // Custom parser to handle quotes
        const tokens = [];
        let cur = '';
        let insideQuote = false;

        for (let c = 0; c < line.length; c++) {
            const ch = line[c];
            if (ch === '"') {
                insideQuote = !insideQuote;
            } else if (ch === ',' && !insideQuote) {
                tokens.push(cur.trim());
                cur = '';
            } else {
                cur += ch;
            }
        }
        tokens.push(cur.trim());

        // CODE,WorkLoadName,Salary,reportname,side
        const [rawCode, rawName, rawSalary, rawReportName, rawSide] = tokens;

        const codeVal = rawCode !== '' && rawCode !== undefined && !isNaN(Number(rawCode)) ? Number(rawCode) : null;
        const nameVal = rawName ? rawName.replace(/^"|"$/g, '').trim() : '';
        const salaryVal = rawSalary !== '' && !isNaN(Number(rawSalary)) ? Number(rawSalary) : 0;
        const reportVal = rawReportName ? rawReportName.replace(/^"|"$/g, '').trim() : '';
        const sideVal = rawSide !== '' && !isNaN(Number(rawSide)) ? Number(rawSide) : 0;

        // Skip rows without meaningful name and code
        if (!nameVal && codeVal === null) continue;

        records.push({
            code: codeVal,
            workloadName: nameVal || (codeVal !== null ? `WORKLOAD ${codeVal}` : 'UNKNOWN'),
            reportName: reportVal || null,
            salary: salaryVal,
            side: sideVal,
            status: 'Active',
        });
    }

    return records;
}

async function runSeed() {
    try {
        console.log('Connecting to database and syncing WorkloadMaster model...');
        await WorkloadMaster.sync({ alter: true });

        const records = parseCsv(rawCsvData);
        console.log(`Parsed ${records.length} records from data.`);

        let inserted = 0;
        let updated = 0;

        for (const item of records) {
            if (item.code !== null) {
                const existing = await WorkloadMaster.findOne({ where: { code: item.code } });
                if (existing) {
                    await existing.update(item);
                    updated++;
                } else {
                    await WorkloadMaster.create(item);
                    inserted++;
                }
            } else {
                await WorkloadMaster.create(item);
                inserted++;
            }
        }

        console.log(`Seeding complete! Inserted: ${inserted}, Updated: ${updated}`);
        process.exit(0);
    } catch (err) {
        console.error('Seeding failed with error:', err);
        process.exit(1);
    }
}

runSeed();
